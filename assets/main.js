/* global window, document, fetch */

function qs(sel, root = document) {
  return root.querySelector(sel);
}

function qsa(sel, root = document) {
  return Array.from(root.querySelectorAll(sel));
}

function el(tag, className) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  return node;
}

function clamp01(x) {
  return Math.max(0, Math.min(1, x));
}

function safeHrefDisable() {
  // Avoid broken navigation if user hasn't filled paper/code links yet.
  qsa("a[data-disabled-link='true']").forEach((a) => {
    a.addEventListener("click", (e) => {
      e.preventDefault();
    });
    a.title = "TODO: set link";
    a.style.opacity = "0.65";
  });
}

function makeVideo(src, opts = {}) {
  const v = document.createElement("video");
  v.src = src;
  v.controls = true;
  v.playsInline = true;
  v.preload = "metadata";
  if (opts.muted) v.muted = true;
  if (opts.loop) v.loop = true;
  return v;
}

function formatTag(tag) {
  if (!tag) return "";
  return tag.replace(/_/g, " ");
}

function looksAutoGenerated(s) {
  if (!s) return false;
  return /auto-generated/i.test(String(s));
}

function cleanCardTitle(title) {
  const t = String(title || "").trim();
  if (!t) return "";
  if (/^concat\s+\d+$/i.test(t)) return ""; // filename-ish titles look bad on the page
  return t;
}

function cleanCardMeta(meta) {
  const m = String(meta || "").trim();
  if (!m) return "";
  if (looksAutoGenerated(m)) return "";
  return m;
}

function wireSyncPair(leftVideo, rightVideo, getEnabled) {
  // Simple sync: mirror play/pause + keep currentTime close during seeking.
  let guard = false;

  function mirrorTime(from, to) {
    if (!getEnabled()) return;
    if (guard) return;
    guard = true;
    try {
      const dt = Math.abs((to.currentTime || 0) - (from.currentTime || 0));
      if (dt > 0.12) to.currentTime = from.currentTime;
    } finally {
      guard = false;
    }
  }

  function mirrorPlay(from, to) {
    if (!getEnabled()) return;
    if (guard) return;
    guard = true;
    try {
      if (from.paused) {
        to.pause();
      } else {
        // Best effort; browsers may block without user gesture.
        void to.play().catch(() => {});
      }
    } finally {
      guard = false;
    }
  }

  leftVideo.addEventListener("play", () => mirrorPlay(leftVideo, rightVideo));
  rightVideo.addEventListener("play", () => mirrorPlay(rightVideo, leftVideo));
  leftVideo.addEventListener("pause", () => mirrorPlay(leftVideo, rightVideo));
  rightVideo.addEventListener("pause", () => mirrorPlay(rightVideo, leftVideo));

  leftVideo.addEventListener("seeking", () => mirrorTime(leftVideo, rightVideo));
  rightVideo.addEventListener("seeking", () => mirrorTime(rightVideo, leftVideo));

  leftVideo.addEventListener("timeupdate", () => mirrorTime(leftVideo, rightVideo));
  rightVideo.addEventListener("timeupdate", () => mirrorTime(rightVideo, leftVideo));
}

function makeCard(entry, settings) {
  const card = el("article", "vcard");
  card.dataset.tags = (entry.tags || []).join(",");

  const pair = el("div", "vpair");
  const hasLeft = Boolean(entry.left && entry.left.src);
  const hasRight = Boolean(entry.right && entry.right.src);
  const isPair = hasLeft && hasRight;
  if (!isPair) pair.classList.add("vpair--single");

  const getSyncEnabled = () => settings.syncEnabled;

  const mkBox = (side, payload) => {
    const box = el("div", "vbox");
    const v = makeVideo(payload.src, { muted: payload.muted ?? true, loop: payload.loop ?? true });
    v.dataset.role = side;
    box.append(v);
    return { box, video: v };
  };

  const videos = [];
  let leftVideo = null;
  let rightVideo = null;

  if (isPair) {
    const left = mkBox(entry.left.label || "Ours", entry.left);
    const right = mkBox(entry.right.label || "Baseline", entry.right);
    pair.append(left.box, right.box);
    videos.push(left.video, right.video);
    leftVideo = left.video;
    rightVideo = right.video;
  } else if (hasLeft) {
    const { box, video } = mkBox(entry.left.label || "Video", entry.left);
    pair.append(box);
    videos.push(video);
  } else if (hasRight) {
    const { box, video } = mkBox(entry.right.label || "Video", entry.right);
    pair.append(box);
    videos.push(video);
  } else {
    const empty = el("div", "skeleton");
    empty.textContent = "Invalid entry: missing left.src/right.src";
    pair.append(empty);
  }

  if (leftVideo && rightVideo) {
    wireSyncPair(leftVideo, rightVideo, getSyncEnabled);
  }

  // Per-card text is intentionally omitted: only section titles and section leads are shown.
  card.append(pair);

  // Autoplay on view is opt-in.
  if (settings.autoplayOnView) {
    const io = new IntersectionObserver(
      (entries) => {
        entries.forEach((it) => {
          if (!it.isIntersecting) return;
          io.unobserve(it.target);
          videos.forEach((v) => {
            // Many browsers require muted for autoplay.
            v.muted = true;
            void v.play().catch(() => {});
          });
        });
      },
      { threshold: clamp01(settings.autoplayThreshold) }
    );
    io.observe(card);
  }

  return card;
}

function makeSection(section, videos, settings) {
  const isCompare = section.id === "compare";
  const hasParts = Array.isArray(section?.parts) && section.parts.length > 0;
  const wrap = el("section", "vsection");
  wrap.id = section.id || "";

  const head = el("div", "section__head");
  const headLeft = el("div", "section__left");
  const h = el("h2", "h2");
  h.textContent = section.title || formatTag(section.id) || "Section";
  const lead = el("p", "section__lead");
  lead.textContent =
    section.lead || "";
  headLeft.append(h, lead);
  head.append(headLeft);

  const gallery = el("div", "gallery");
  gallery.dataset.section = section.id || "";

  function makeLoopingCarousel(items, perPage, carouselClass) {
    const carousel = el("div", `carousel ${carouselClass}`.trim());
    const scroller = el("div", "gallery gallery--carousel");
    scroller.dataset.section = section.id || "";

    const pages = [];
    for (let i = 0; i < items.length; i += perPage) {
      const page = el("div", "carousel__page");
      for (let j = i; j < Math.min(i + perPage, items.length); j++) {
        page.append(makeCard(items[j], settings));
      }
      pages.push(page);
      scroller.append(page);
    }

    const btnPrev = el("button", "carousel__btn carousel__btn--prev");
    btnPrev.type = "button";
    btnPrev.setAttribute("aria-label", "Previous");
    btnPrev.textContent = "‹";

    const btnNext = el("button", "carousel__btn carousel__btn--next");
    btnNext.type = "button";
    btnNext.setAttribute("aria-label", "Next");
    btnNext.textContent = "›";

    const dots = el("div", "carousel__dots");
    const dotBtns = pages.map((_, idx) => {
      const b = el("button", "dotbtn");
      b.type = "button";
      b.setAttribute("aria-label", `Go to page ${idx + 1}`);
      b.addEventListener("click", () => go(idx));
      dots.append(b);
      return b;
    });

    let current = 0;

    function setActive(idx) {
      dotBtns.forEach((b, i) => b.classList.toggle("is-active", i === idx));
    }

    function go(idx) {
      const n = pages.length;
      if (n === 0) return;
      current = ((idx % n) + n) % n;
      const target = pages[current];
      scroller.scrollTo({ left: target.offsetLeft, top: 0, behavior: "smooth" });
      setActive(current);
    }

    btnPrev.addEventListener("click", () => go(current - 1));
    btnNext.addEventListener("click", () => go(current + 1));

    // Update dots when user scrolls manually.
    let raf = 0;
    scroller.addEventListener("scroll", () => {
      if (raf) return;
      raf = window.requestAnimationFrame(() => {
        raf = 0;
        let best = 0;
        let bestDist = Infinity;
        const x = scroller.scrollLeft;
        pages.forEach((p, i) => {
          const d = Math.abs(p.offsetLeft - x);
          if (d < bestDist) {
            bestDist = d;
            best = i;
          }
        });
        if (best !== current) {
          current = best;
          setActive(current);
        }
      });
    });

    window.addEventListener("resize", () => {
      go(current);
    });

    setActive(0);

    // If only one page, hide chrome to keep the section clean.
    if (pages.length <= 1) {
      btnPrev.style.display = "none";
      btnNext.style.display = "none";
      dots.style.display = "none";
    }

    carousel.append(scroller, btnPrev, btnNext, dots);
    return carousel;
  }

  if (hasParts) {
    const partsWrap = el("div", "parts");
    section.parts.forEach((part, idx) => {
      const partWrap = el("div", "section__part");
      const pHead = el("div", "part__head");
      const pTitle = el("h3", "part__title");
      pTitle.textContent = part?.title || `Part ${idx + 1}`;
      pHead.append(pTitle);

      const pLeadText = String(part?.lead || "").trim();
      if (pLeadText) {
        const pLead = el("p", "part__lead");
        pLead.textContent = pLeadText;
        pHead.append(pLead);
      }

      const pVids = Array.isArray(part?.videos) ? part.videos : [];
      if (pVids.length === 0) {
        const empty = el("div", "skeleton");
        empty.innerHTML =
          "No videos yet for this part. Add mp4 files under <span class='kbd'>video/" +
          (section.id || "SECTION") +
          "/" +
          (part?.id ? String(part.id) + "/" : "") +
          "</span> and update <span class='kbd'>project_page/assets/data/videos.json</span>. Then run the sync command in README to regenerate <span class='kbd'>videos.js</span> for offline.";
        partWrap.append(pHead, empty);
      } else {
        // Ablation parts: Nerfies-like looping carousel, 1 row with 2 videos per page.
        if (section.id === "ablation") {
          const carousel = makeLoopingCarousel(pVids, 2, "carousel--row2");
          partWrap.append(pHead, carousel);
        } else {
          const pGallery = el("div", "gallery");
          pGallery.dataset.section = section.id || "";
          if (part?.id) pGallery.dataset.part = String(part.id);
          pVids.forEach((entry) => {
            pGallery.append(makeCard(entry, settings));
          });
          partWrap.append(pHead, pGallery);
        }
      }

      partsWrap.append(partWrap);
    });

    wrap.append(head, partsWrap);
    return wrap;
  }

  if (!Array.isArray(videos) || videos.length === 0) {
    const empty = el("div", "skeleton");
    empty.innerHTML =
      "No videos yet for this section. Add mp4 files under <span class='kbd'>video/" +
      (section.id || "SECTION") +
      "/</span> and update <span class='kbd'>project_page/assets/data/videos.json</span>. Then run the sync command in README to regenerate <span class='kbd'>videos.js</span> for offline.";
    gallery.append(empty);
    wrap.append(head, gallery);
    return wrap;
  }

  if (!isCompare) {
    videos.forEach((entry) => {
      gallery.append(makeCard(entry, settings));
    });
    wrap.append(head, gallery);
    return wrap;
  }

  // Compared with SOTA:
  // - 2 rows visible per page (2 cards stacked)
  // - left/right nav + dots
  const carousel = el("div", "carousel carousel--compare");
  const scroller = el("div", "gallery gallery--carousel");
  scroller.dataset.section = section.id || "";

  const pages = [];
  for (let i = 0; i < videos.length; i += 2) {
    const page = el("div", "carousel__page");
    page.append(makeCard(videos[i], settings));
    if (i + 1 < videos.length) page.append(makeCard(videos[i + 1], settings));
    pages.push(page);
    scroller.append(page);
  }

  const btnPrev = el("button", "carousel__btn carousel__btn--prev");
  btnPrev.type = "button";
  btnPrev.setAttribute("aria-label", "Previous");
  btnPrev.textContent = "‹";

  const btnNext = el("button", "carousel__btn carousel__btn--next");
  btnNext.type = "button";
  btnNext.setAttribute("aria-label", "Next");
  btnNext.textContent = "›";

  const dots = el("div", "carousel__dots");
  const dotBtns = pages.map((_, idx) => {
    const b = el("button", "dotbtn");
    b.type = "button";
    b.setAttribute("aria-label", `Go to page ${idx + 1}`);
    b.addEventListener("click", () => go(idx));
    dots.append(b);
    return b;
  });

  let current = 0;

  function setActive(idx) {
    dotBtns.forEach((b, i) => b.classList.toggle("is-active", i === idx));
  }

  function go(idx) {
    const n = pages.length;
    if (n === 0) return;
    current = ((idx % n) + n) % n;
    const target = pages[current];
    scroller.scrollTo({ left: target.offsetLeft, top: 0, behavior: "smooth" });
    setActive(current);
  }

  btnPrev.addEventListener("click", () => go(current - 1));
  btnNext.addEventListener("click", () => go(current + 1));

  // Update dots when user scrolls manually.
  let raf = 0;
  scroller.addEventListener("scroll", () => {
    if (raf) return;
    raf = window.requestAnimationFrame(() => {
      raf = 0;
      // Find nearest page by distance to left edge.
      let best = 0;
      let bestDist = Infinity;
      const x = scroller.scrollLeft;
      pages.forEach((p, i) => {
        const d = Math.abs(p.offsetLeft - x);
        if (d < bestDist) {
          bestDist = d;
          best = i;
        }
      });
      if (best !== current) {
        current = best;
        setActive(current);
      }
    });
  });

  window.addEventListener("resize", () => {
    // Keep current page aligned after resizes.
    go(current);
  });

  setActive(0);

  carousel.append(scroller, btnPrev, btnNext, dots);
  wrap.append(head, carousel);
  return wrap;
}

async function loadGallery() {
  const sectionsRoot = qs("#sections");
  const syncToggle = qs("#toggleSync");
  const autoplayToggle = qs("#toggleAutoplay");

  const settings = {
    syncEnabled: true,
    autoplayOnView: false,
    autoplayThreshold: 0.35,
  };

  if (syncToggle) {
    settings.syncEnabled = Boolean(syncToggle.checked);
    syncToggle.addEventListener("change", () => {
      settings.syncEnabled = Boolean(syncToggle.checked);
    });
  }

  if (autoplayToggle) {
    settings.autoplayOnView = Boolean(autoplayToggle.checked);
    autoplayToggle.addEventListener("change", () => {
      settings.autoplayOnView = Boolean(autoplayToggle.checked);
      // Changing this after render is not retroactive (by design).
    });
  }

  const isFile = window.location && window.location.protocol === "file:";
  let data = null;

  // Default behavior:
  // - file:// (double-click): use videos.js (no fetch required)
  // - http(s)://: use videos.json (easy to edit + works on GitHub Pages)
  if (isFile) {
    data = window.__PROJECT_PAGE_VIDEOS__ || null;
  } else {
    try {
      const res = await fetch("assets/data/videos.json", { cache: "no-store" });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      data = await res.json();
    } catch (e) {
      data = window.__PROJECT_PAGE_VIDEOS__ || null;
    }
  }

  if (!data) {
    sectionsRoot.innerHTML = "";
    const err = el("div", "skeleton");
    err.textContent =
      "Failed to load video config. For double-click opening, ensure assets/data/videos.js exists. For HTTP hosting, ensure assets/data/videos.json exists.";
    sectionsRoot.append(err);
    return;
  }

  const sections = Array.isArray(data?.sections) ? data.sections : [];
  sectionsRoot.innerHTML = "";

  if (sections.length === 0) {
    const empty = el("div", "skeleton");
    empty.innerHTML =
      "No sections configured yet. Edit <span class='kbd'>project_page/assets/data/videos.json</span> and add section entries.";
    sectionsRoot.append(empty);
    return;
  }

  sections.forEach((section) => {
    const vids = Array.isArray(section?.videos) ? section.videos : [];
    sectionsRoot.append(makeSection(section, vids, settings));
  });
}

